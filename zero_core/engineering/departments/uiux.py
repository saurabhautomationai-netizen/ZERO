    def review_design_package(self, pkg: UIDesignPackage) -> UIReviewResult:
        """Executes the internal design review stage checking completeness, accessibility, and finish."""
        findings = []
        score = 100

        if not pkg.pages:
            findings.append(UIReviewFinding("CONSISTENCY", "HIGH", "No pages identified in page inventory.", "Extract pages from SRS requirements."))
            score -= 40

        if not pkg.design_system.get("colors"):
            findings.append(UIReviewFinding("CONSISTENCY", "HIGH", "Missing color tokens in design system.", "Define contrast-compliant palette."))
            score -= 30

        # Accessibility checks
        colors = pkg.design_system.get("colors", {})
        bg = colors.get("background_primary", "#000000")
        text = colors.get("text_primary", "#ffffff")
        if bg.lower() == text.lower():
            findings.append(UIReviewFinding("ACCESSIBILITY", "HIGH", "Zero contrast between background and text color.", "Ensure minimum 4.5:1 contrast ratio."))
            score -= 30

        # Commercial finish check
        if len(pkg.pages) > 20:
            findings.append(UIReviewFinding("FINISH_GATE", "MEDIUM", "Excessive initial page count creates cognitive clutter.", "Consolidate auxiliary pages into tabs."))
            score -= 15

        verdict = "PASS" if score >= 80 and not any(f.severity == "HIGH" for f in findings) else "NEEDS_REVISION"
        summary = f"UI Review Score: {score}/100. Verdict: {verdict} ({len(findings)} findings)."

        return UIReviewResult(verdict=verdict, score=score, findings=findings, summary=summary)

    def run_task(self, context: ProjectContextPackage) -> WorkerResult:
        """Executes the complete UI/UX pipeline for the given project context."""
        logger.info("UIUXDepartmentCoordinator executing task: %s for %s", context.task_title, context.project_name)

        proj_id = context.project_id
        self.revision_counter[proj_id] = self.revision_counter.get(proj_id, 0) + 1
        rev_count = self.revision_counter[proj_id]

        if rev_count > MAX_UI_REVISIONS:
            logger.warning("UI/UX revision loop exceeded limit (%d > %d)", rev_count, MAX_UI_REVISIONS)
            return WorkerResult(
                task_id=context.task_id,
                worker_id=self.worker_id,
                status="BLOCKED",
                summary=f"UI/UX Design revisions exceeded maximum limit ({MAX_UI_REVISIONS}). Escaped to HITL review.",
                analysis="Maximum design iterations reached without consensus. Requires human design owner direction.",
                requires_human=True,
                recommended_next_action="Human Product Owner to review design options and provide explicit direction",
            )

        # 1. Existing UI Audit
        ui_audit = self.audit_existing_ui(context)

        # 2. Page Inventory
        pages = self.generate_page_inventory(context)

        # 3. Design System Tokens
        ds = self.generate_design_system(context.project_name)

        # 4. User Flows
        flows = [
            f"User lands on Dashboard -> Views live telemetry and recent items",
            f"User navigates to primary data view ({pages[1]['name'] if len(pages) > 1 else 'Items'}) -> Searches & filters records",
            f"User clicks record -> Inspects detail panel / drawer -> Performs primary domain action",
        ]

        # 5. Component Inventory
        components = [
            "Navigation Shell (Responsive Desktop Sidebar / Mobile Bottom Bar)",
            "Metric KPI Cards (Delta indicators & micro sparklines)",
            "Data Table (Sortable headers, row selection, pagination)",
            "Action Toolbar (Search input, filter pill dropdowns, export action)",
            "Detail Drawer / Slide-Over (Tabbed sub-sections and audit timeline)",
            "Feedback Toast & Confirmation Modals",
        ]

        # 6. Interactive Prototype
        prototype_html = self.generate_interactive_prototype(context.project_name, pages, ds)

        # 7. Package Assembly
        design_pkg = UIDesignPackage(
            project_id=context.project_id,
            project_name=context.project_name,
            version=f"v1.{rev_count}.0",
            pages=pages,
            user_flows=flows,
            design_system=ds,
            component_inventory=components,
            responsive_strategy="Fluid CSS Grid + Flexbox (Breakpoints: Mobile < 640px, Tablet < 1024px, Desktop >= 1024px)",
            motion_strategy="Subtle 200ms ease-out transitions for cards and state switches with full reduced-motion support.",
            current_ui_audit=ui_audit,
            prototype_html=prototype_html,
            generated_artifacts=[
                "docs/UIUX_SPEC.md",
                "docs/PAGE_INVENTORY.md",
                "docs/USER_FLOWS.md",
                "docs/DESIGN_SYSTEM.md",
                "docs/COMPONENT_INVENTORY.md",
                "docs/PROTOTYPE.html",
                "docs/UI_REVIEW.md",
            ],
        )

        # 8. Internal UI Review
        review = self.review_design_package(design_pkg)
        design_pkg.review_verdict = review.verdict

        # If review needs revision, report back for bounded repair
        if not review.is_pass:
            return WorkerResult(
                task_id=context.task_id,
                worker_id=self.worker_id,
                status="NEEDS_REVIEW",
                summary=f"UI/UX Design produced with review status {review.verdict} (Score: {review.score}/100)",
                analysis=f"Review findings require correction:\n" + "\n".join(f"- [{f.category}] {f.description}" for f in review.findings),
                artifacts_created=design_pkg.generated_artifacts,
                recommended_next_action="Address review findings in next design iteration",
            )

        # 9. Stop at HITL Gate 2
        approval_req = self.approval_engine.evaluate(
            action_type="UI_UX_DESIGN_APPROVAL",
            target=context.project_name,
            parameters={
                "project_id": context.project_id,
                "version": design_pkg.version,
                "page_count": len(pages),
                "pages": [p["name"] for p in pages],
                "review_score": review.score,
            },
            declared_risk=RiskLevel.HIGH,  # Gate 2 requires human approval
        )

        analysis_md = (
            f"# UI/UX Design Specification: {context.project_name} ({design_pkg.version})\n\n"
            f"**Review Status**: `{review.verdict}` (Score: {review.score}/100)\n\n"
            f"## 1. Page Inventory ({len(pages)} pages)\n"
            + "\n".join(f"- **{p['name']}** (`{p['path']}`): {p['purpose']}" for p in pages)
            + f"\n\n## 2. Design System\n"
            f"- **Palette**: Background `{ds['colors']['background_primary']}`, Card `{ds['colors']['surface_card']}`, Accent `{ds['colors']['accent_primary']}`\n"
            f"- **Typography**: `{ds['typography']['font_family']}`\n"
            f"- **Responsive**: {design_pkg.responsive_strategy}\n"
            f"- **Motion**: {design_pkg.motion_strategy}\n\n"
            f"## 3. High-Fidelity Prototype\n"
            f"- Saved to `docs/PROTOTYPE.html` (interactive HTML preview).\n\n"
            f"## 4. Human-In-The-Loop (HITL) Gate 2\n"
            f"- **Approval Request ID**: `{approval_req.request_id}`\n"
            f"- **Status**: `APPROVAL_PENDING` (Human Product Owner decision required before frontend implementation)."
        )

        return WorkerResult(
            task_id=context.task_id,
            worker_id=self.worker_id,
            status="SUCCESS",
            summary=f"UI/UX Design package {design_pkg.version} completed and verified. Awaiting HITL Gate 2 Approval.",
            analysis=analysis_md,
            files_created=design_pkg.generated_artifacts,
            artifacts_created=design_pkg.generated_artifacts,
            acceptance_criteria_results={crit: True for crit in context.acceptance_criteria},
            requires_human=True,
            recommended_next_action="Await Human Product Owner UI/UX Gate 2 approval before starting frontend implementation",
            execution_metadata={
                "gate_id": "GATE_2_UIUX",
                "approval_request_id": approval_req.request_id,
                "review_score": review.score,
                "version": design_pkg.version,
            },
        )


