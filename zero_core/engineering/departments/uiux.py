MAX_UI_REVISIONS = 3


@dataclass
class UIReviewFinding:
    category: str  # "ACCESSIBILITY" | "CONSISTENCY" | "USABILITY" | "FINISH_GATE"
    severity: str  # "LOW" | "MEDIUM" | "HIGH"
    description: str
    recommendation: str


@dataclass
class UIReviewResult:
    verdict: str  # "PASS" | "NEEDS_REVISION" | "REJECT"
    score: int    # 0 - 100
    findings: List[UIReviewFinding] = field(default_factory=list)
    summary: str = ""
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @property
    def is_pass(self) -> bool:
        return self.verdict == "PASS"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "verdict": self.verdict,
            "score": self.score,
            "findings": [asdict(f) for f in self.findings],
            "summary": self.summary,
            "timestamp": self.timestamp,
        }


@dataclass
class UIDesignPackage:
    """Complete, cohesive product design package generated by the UI/UX Department."""
    project_id: str
    project_name: str
    version: str = "v1.0.0"
    pages: List[Dict[str, str]] = field(default_factory=list)
    user_flows: List[str] = field(default_factory=list)
    design_system: Dict[str, Any] = field(default_factory=dict)
    component_inventory: List[str] = field(default_factory=list)
    responsive_strategy: str = ""
    motion_strategy: str = ""
    accessibility_status: str = "WCAG_2_1_AA_COMPLIANT"
    review_verdict: str = "PENDING"
    prototype_html: str = ""
    generated_artifacts: List[str] = field(default_factory=list)
    current_ui_audit: Optional[Dict[str, Any]] = None

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


class UIUXDepartmentCoordinator(EngineeringWorker):
    """Lead coordinator for the UI/UX Department.
    
    Coordinates UX Architects, UI Designers, Accessibility Auditors, and
    UI Finish-Gate Reviewers to produce a unified, review-validated design package.
    """

    def __init__(
        self,
        approval_engine: Optional[ApprovalPolicyEngine] = None,
        agent_registry: Optional[AgentRegistry] = None,
    ):
        super().__init__(
            worker_id="worker_uiux_designer",
            name="UI/UX Department Coordinator",
            worker_type=WorkerType.NATIVE,
            capabilities=[
                WorkerCapability.UI_DESIGN,
                WorkerCapability.UX_ARCHITECTURE,
                WorkerCapability.DOCUMENTATION,
            ],
            transport="INTERNAL_CALL",
            risk_level="MEDIUM",
        )
        self.approval_engine = approval_engine or DEFAULT_APPROVAL_ENGINE
        self.agent_registry = agent_registry
        self.revision_counter: Dict[str, int] = {}  # project_id -> count

    def audit_existing_ui(self, context: ProjectContextPackage) -> Dict[str, Any]:
        """Audits existing frontend assets and classifies them into KEEP, IMPROVE, REDESIGN, REMOVE, MISSING."""
        frontend_files = [
            fpath for fpath in context.relevant_files.keys()
            if any(fpath.endswith(ext) for ext in (".html", ".css", ".js", ".jsx", ".tsx", ".vue"))
        ]

        keep = []
        improve = []
        redesign = []
        missing = []

        if frontend_files:
            for f in frontend_files:
                if "base" in f or "reset" in f or "var" in f:
                    keep.append(f)
                elif "component" in f or "card" in f or "nav" in f:
                    improve.append(f)
                else:
                    redesign.append(f)
        else:
            missing.extend(["Design System Tokens", "Global Layout Shell", "Navigation Shell", "Responsive Breakpoints"])

        return {
            "is_existing_ui": len(frontend_files) > 0,
            "inspected_files": frontend_files,
            "classification": {
                "keep": keep,
                "improve": improve,
                "redesign": redesign,
                "remove": [],
                "missing": missing,
            },
            "summary": (
                f"Existing UI Audit: {len(frontend_files)} frontend files inspected. "
                f"Preserving {len(keep)} base styles, improving {len(improve)} components, "
                f"and modernizing {len(redesign)} page views."
            ),
        }

